#!/usr/bin/env node
/* Builds js/uscounties.js: every county's outline as an SVG path in the same Albers USA projection
   and 975 x 610 canvas as js/usmap.js, grouped by state, with its name. The home page loads it only
   when a card draws one state county by county.

   Source: us-atlas counties-10m.json (US Census TIGER, public domain). Usage:
     curl -L -o /tmp/counties-10m.json https://cdn.jsdelivr.net/npm/us-atlas@3/counties-10m.json
     node tools/build-us-counties.js /tmp/counties-10m.json > js/uscounties.js */
'use strict';
const fs = require('fs');
const { albersUsa, simplify, FIPS } = require('./build-us-map.js');

function build(topo, tol) {
  const project = albersUsa();
  const { scale, translate } = topo.transform;
  const arcs = topo.arcs.map((arc) => {
    let x = 0, y = 0;
    return arc.map(([dx, dy]) => { x += dx; y += dy; return project(y * scale[1] + translate[1], x * scale[0] + translate[0]); });
  });
  const ring = (indexes) => {
    const pts = [];
    for (const i of indexes) {
      const a = i < 0 ? arcs[~i].slice().reverse() : arcs[i];
      for (let k = pts.length ? 1 : 0; k < a.length; k++) pts.push(a[k]);
    }
    return pts;
  };
  const byState = {};
  for (const g of topo.objects.counties.geometries) {
    const st = FIPS[String(g.id).slice(0, 2)];
    if (!st) continue;
    let d = '';
    for (const poly of (g.type === 'Polygon' ? [g.arcs] : g.arcs)) {
      for (const r of poly) {
        const pts = simplify(ring(r), tol);
        if (pts.length < 4) continue;
        d += 'M' + pts.map(([x, y]) => `${x.toFixed(1)},${y.toFixed(1)}`).join('L') + 'Z';
      }
    }
    if (!d) continue;
    (byState[st] = byState[st] || []).push({ id: String(g.id), name: g.properties.name, d });
  }
  for (const st of Object.keys(byState)) byState[st].sort((a, b) => a.id.localeCompare(b.id));
  return byState;
}

if (require.main === module) {
  const src = process.argv[2];
  if (!src) { console.error('usage: node tools/build-us-counties.js counties-10m.json > js/uscounties.js'); process.exit(1); }
  const topo = JSON.parse(fs.readFileSync(src, 'utf8'));
  const byState = build(topo, Number(process.env.TOL || 0.5));
  process.stdout.write(`/* US county outlines, by state: us-atlas counties-10m (US Census TIGER, public domain), drawn with the
   same Albers USA projection as js/usmap.js onto 975 x 610. Generated by tools/build-us-counties.js; don't edit by hand. */
(function (root) {
  'use strict';
  const api = { byState: ${JSON.stringify(byState)} };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.USCounties = api;
})(typeof window !== 'undefined' ? window : globalThis);
`);
}
module.exports = { build };
