#!/usr/bin/env node
// Builds js/zipdata.js: one row per 3-digit ZIP prefix (the USPS sectional center that sorts the
// mail for that area) with its center point and the place that has the most ZIPs in it. That is
// enough to put any US ZIP code on the map without a network request; Geo.refine() fetches the
// exact place for a full 5-digit ZIP when it can.
//
// Input: the GeoNames US postal-code file (download.geonames.org/export/zip/US.zip, CC BY 4.0).
// Usage: node tools/build-zip-table.js path/to/US.txt
const fs = require('fs');
const path = require('path');

const src = process.argv[2];
if (!src) { console.error('usage: node tools/build-zip-table.js US.txt'); process.exit(1); }
const STATES = new Set(('AL AK AZ AR CA CO CT DE DC FL GA HI ID IL IN IA KS KY LA ME MD MA MI MN MS MO MT NE NV NH NJ NM NY NC ND OH OK OR PA RI SC SD TN TX UT VT VA WA WV WI WY').split(' '));
const byPrefix = new Map();
for (const line of fs.readFileSync(src, 'utf8').split('\n')) {
  const c = line.split('\t');
  if (c.length < 11) continue;
  const [, zip, place, , state, , , , , lat, lng] = c;
  if (!/^\d{5}$/.test(zip) || !STATES.has(state) || !lat || !lng) continue;
  const p = zip.slice(0, 3);
  if (!byPrefix.has(p)) byPrefix.set(p, []);
  byPrefix.get(p).push({ zip, place, state, lat: +lat, lng: +lng });
}
const rows = [];
for (const [p, zips] of [...byPrefix].sort()) {
  const lat = zips.reduce((s, z) => s + z.lat, 0) / zips.length;
  const lng = zips.reduce((s, z) => s + z.lng, 0) / zips.length;
  const counts = new Map();
  for (const z of zips) {
    const k = `${z.place}|${z.state}`;
    const e = counts.get(k) || { n: 0, d: Infinity };
    e.n++;
    e.d = Math.min(e.d, Math.hypot(z.lat - lat, z.lng - lng));
    counts.set(k, e);
  }
  const [best] = [...counts].sort((a, b) => b[1].n - a[1].n || a[1].d - b[1].d)[0];
  const [place, state] = best.split('|');
  // A real ZIP close to the center, so "use my location" lands on one that exists.
  const sample = zips.slice().sort((a, b) => Math.hypot(a.lat - lat, a.lng - lng) - Math.hypot(b.lat - lat, b.lng - lng))[0];
  rows.push([p, lat.toFixed(2), lng.toFixed(2), place.replace(/[|;]/g, ''), state, sample.zip.slice(3)].join('|'));
}
const out = `/* Generated by tools/build-zip-table.js from GeoNames postal-code data (CC BY 4.0). Do not edit by hand.
   Each row: 3-digit ZIP prefix | center latitude | center longitude | main place | state | last two digits of a real ZIP near the center. */
(function (root) {
  'use strict';
  const rows = ${JSON.stringify(rows.join(';'))};
  if (typeof module !== 'undefined' && module.exports) module.exports = rows;
  else root.ZIP_ROWS = rows;
})(typeof window !== 'undefined' ? window : globalThis);
`;
fs.writeFileSync(path.join(__dirname, '..', 'js', 'zipdata.js'), out);
console.log(`Wrote ${rows.length} ZIP prefixes to js/zipdata.js (${(out.length / 1024).toFixed(1)} KB)`);
